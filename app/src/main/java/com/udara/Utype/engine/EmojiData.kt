    fun byCategory(category: EmojiCategory): List<EmojiEntry> =
        allEmojis.filter { it.category == category }

    fun search(query: String): List<EmojiEntry> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return allEmojis
        return allEmojis.filter { it.keywords.contains(q) || it.emoji.contains(q) }
    }
